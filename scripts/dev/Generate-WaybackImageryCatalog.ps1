param(
    [string]$OutputPath = (Join-Path $PSScriptRoot '..\..\GisProAddinWorkbench.AddIn\Modules\Imagery\Generated\ImageryServiceCatalog.Wayback.g.cs')
)

$ErrorActionPreference = 'Stop'

$capabilitiesUrl = 'https://wayback.maptiles.arcgis.com/arcgis/rest/services/World_Imagery/MapServer/WMTS/1.0.0/WMTSCapabilities.xml'
$waybackCategory = -join @([char]0x5386, [char]0x53f2, [char]0x5f71, [char]0x50cf)
$waybackTag = -join @([char]0x5386, [char]0x53f2)
$waybackSymbol = [string]([char]0x56de)

function Convert-ToCSharpStringLiteral {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Value
    )

    $builder = [System.Text.StringBuilder]::new()
    foreach ($ch in $Value.ToCharArray()) {
        if ($ch -eq '"') {
            [void]$builder.Append('\"')
            continue
        }

        if ($ch -eq '\') {
            [void]$builder.Append('\\')
            continue
        }

        if ($ch -eq "`r") {
            continue
        }

        if ($ch -eq "`n") {
            [void]$builder.Append('\n')
            continue
        }

        if ($ch -eq "`t") {
            [void]$builder.Append('\t')
            continue
        }

        $code = [int][char]$ch
        if ($code -lt 32 -or $code -gt 126) {
            [void]$builder.Append(('\u{0:X4}' -f $code))
            continue
        }

        [void]$builder.Append($ch)
    }

    return $builder.ToString()
}

function New-WaybackPreviewUrl {
    param(
        [Parameter(Mandatory = $true)]
        [string]$MapLayerId
    )

    return "BuildWaybackPreviewUrl(`"$MapLayerId`")"
}

try {
    $xml = [xml](Invoke-WebRequest -Uri $capabilitiesUrl -UseBasicParsing).Content
}
catch {
    throw "Unable to download Wayback capabilities from $capabilitiesUrl. $($_.Exception.Message)"
}

$layers = $xml.SelectNodes("//*[local-name()='Contents']/*[local-name()='Layer']")
if ($null -eq $layers -or $layers.Count -eq 0) {
    throw 'No Wayback layers were found in the capabilities document.'
}

$sortOrder = 130
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// <auto-generated />')
$lines.Add("// Generated from $capabilitiesUrl")
$lines.Add('// Do not edit manually.')
$lines.Add('using System.Collections.Generic;')
$lines.Add('')
$lines.Add('namespace GisProAddinWorkbench.AddIn.Modules.Imagery;')
$lines.Add('')
$lines.Add('internal static partial class ImageryServiceCatalog')
$lines.Add('{')
$lines.Add('    private static IReadOnlyList<ImageryServicePreset> CreateWaybackPresets()')
$lines.Add('    {')
$lines.Add('        return')
$lines.Add('        [')

foreach ($layer in $layers) {
    $titleNode = $layer.SelectSingleNode("./*[local-name()='Title']")
    $identifierNode = $layer.SelectSingleNode("./*[local-name()='Identifier']")
    $resourceNode = $layer.SelectSingleNode("./*[local-name()='ResourceURL']")

    if ($null -eq $titleNode -or $null -eq $identifierNode -or $null -eq $resourceNode) {
        throw 'Unable to parse Wayback layer metadata.'
    }

    $title = $titleNode.InnerText.Trim()
    $identifier = $identifierNode.InnerText.Trim()

    if ($title -notmatch 'Wayback (\d{4}-\d{2}-\d{2})') {
        throw "Unexpected Wayback title: $title"
    }

    $date = $Matches[1]
    $template = $resourceNode.GetAttribute('template')
    if ($template -notmatch 'tile/([0-9]+)/') {
        throw "Unable to resolve Wayback map layer id for $identifier"
    }

    $mapLayerId = $Matches[1]
    $displayName = "Wayback $date"
    $summary = "ArcGIS Wayback $waybackCategory, date $date."

    $lines.Add('            CreateWmtsPreset(')
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $identifier)))
    $lines.Add('                "Esri",')
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $displayName)))
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $waybackCategory)))
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $summary)))
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $waybackTag)))
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $waybackSymbol)))
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $identifier)))
    $lines.Add(('                "{0}",' -f (Convert-ToCSharpStringLiteral $capabilitiesUrl)))
    $lines.Add(('                {0},' -f (New-WaybackPreviewUrl -MapLayerId $mapLayerId)))
    $lines.Add('                ImageryLayerRole.Base,')
    $lines.Add(('                {0},' -f $sortOrder))
    $lines.Add('                CreateBrush("#2563EB"),')
    $lines.Add('                CreateBrush("#DBEAFE")),')

    $sortOrder++
}

$lines.Add('        ];')
$lines.Add('    }')
$lines.Add('}')

$outputDirectory = Split-Path -Parent $OutputPath
if (-not (Test-Path $outputDirectory)) {
    New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
}

[System.IO.File]::WriteAllLines($OutputPath, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $OutputPath with $($layers.Count) Wayback presets."
